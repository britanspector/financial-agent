def report_body(company: dict[str, object], index: int) -> str:
    name = str(company["name"])
    view = company["views"][index]
    period = company["periods"][index]
    revenue = company["revenue"][index]
    profit = company["profit"][index]
    margin = company["margin"][index]
    comparison = "首次覆盖，基准判断以当前订单和经营数据为起点。" if index == 0 else (
        "相较前次报告，本次下调短期收入与利润判断，主要反映确认节奏和价格压力。" if index == 1 else
        "相较前次报告，本次上修盈利判断，但尚未恢复到最初的乐观假设。"
    )
    metric_name = "净息差（%）" if name == "安岳银行" else "毛利率（%）"
    table = ""
    if index == 2:
        table = (
            "\n## 核心指标\n\n"
            "| 指标 | 前期判断 | 本期判断 | 变化说明 |\n"
            "| --- | ---: | ---: | --- |\n"
            f"| 营业收入（亿元） | {company['revenue'][1]} | {revenue} | 结合最新经营进度调整 |\n"
            f"| 归母净利润（亿元） | {company['profit'][1]} | {profit} | 反映成本与产品结构变化 |\n"
            f"| {metric_name} | {company['margin'][1]} | {margin} | 口径与本报告期一致 |\n"
        )
    return (
        f"# {name}：{period}经营跟踪与展望\n\n"
        "## 核心观点\n\n"
        f"{view} 本报告关注{company['driver']}，当前判断建立在公开经营信息和 synthetic 假设上。"
        f"我们预计本口径营业收入约为{revenue}亿元，归母净利润约为{profit}亿元，"
        f"{metric_name}约为{margin}。这些数值是本次报告的独立预测，不应与其他日期报告直接拼接。\n\n"
        "## 经营观察\n\n"
        f"{name}所属{company['industry']}行业，需求、交付和收入确认之间存在时间差。"
        f"本期主要正面因素是{company['driver']}；需要持续观察的变量是{company['risk']}。"
        "短期单季波动不改变中期逻辑，但会改变利润兑现路径和估值容忍度。\n\n"
        "## 与前次判断的差异\n\n"
        f"{comparison} 调整针对预测数据，不回溯修改旧报告，使不同发布时间的观点可以独立比较。\n"
        f"{table}\n"
        "## 风险提示\n\n"
        f"主要风险包括{company['risk']}、关键经营指标不及预期以及行业竞争加剧。"
        "本文为 synthetic 研究样本，不构成投资建议。\n"
    )


def faq_body(title: str, answer: str, version: str, effective_date: str) -> str:
    return (
        f"# {title}\n\n## 问题\n\n{title}\n\n## 回答\n\n{answer}\n\n"
        f"## 适用说明\n\n本答案版本为 {version}，自 {effective_date} 起生效。"
        "如页面规则、业务协议或交易场所规则另有要求，以当前有效规则为准。\n"
    )


def policy_body(title: str, text: str, note: str) -> str:
    return (
        f"# {title}\n\n## 一、主要内容\n\n{text}\n\n"
        f"## 二、适用与衔接\n\n{note}\n\n"
        "## 三、风险与解释\n\n本文件为 synthetic 知识库样本。涉及操作边界时，应结合适用日期、发布机构及当前有效版本理解。\n"
    )


def write_document(relative_path: str, content: str) -> None:
    target = KNOWLEDGE_ROOT / relative_path
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content, encoding="utf-8", newline="\n")


def generate() -> None:
    documents: list[dict[str, object]] = []
    for company in COMPANIES:
        for index in range(3):
            document_id = f"RR-{company['slug']}-{company['dates'][index].replace('-', '')}-{index + 1:02d}"
            path = f"research_reports/{document_id}.md"
            title = f"{company['name']}：{company['periods'][index]}经营跟踪与展望"
            metadata = {
                "document_id": document_id, "source_type": "research_report", "title": title,
                "company": company["name"], "broker": BROKERS[company["brokers"][index]],
                "publish_date": company["dates"][index], "report_period": company["periods"][index],
            }
            write_document(path, report_body(company, index))
            documents.append({"document_id": document_id, "path": path, "metadata": metadata})

    faq_versions: dict[str, int] = {}
    for family, category, title, version, effective_date, answer in FAQS:
        faq_versions[family] = faq_versions.get(family, 0) + 1
        document_id = f"FAQ-{family}-V{faq_versions[family]}"
        path = f"faq/{document_id}.md"
        metadata = {
            "document_id": document_id, "source_type": "faq", "title": title,
            "category": category, "version": version, "effective_date": effective_date,
        }
        write_document(path, faq_body(title, answer, version, effective_date))
        documents.append({"document_id": document_id, "path": path, "metadata": metadata})

    for document_id, title, issuer, publish_date, effective_date, status, text, note in POLICIES:
        path = f"announcements_policies/{document_id}.md"
        metadata = {
            "document_id": document_id, "source_type": "announcement_policy", "title": title,
            "issuer": issuer, "publish_date": publish_date, "effective_date": effective_date, "status": status,
        }
        write_document(path, policy_body(title, text, note))
        documents.append({"document_id": document_id, "path": path, "metadata": metadata})

    manifest = {"schema_version": "0.1", "documents": documents}
    KNOWLEDGE_ROOT.mkdir(parents=True, exist_ok=True)
    (KNOWLEDGE_ROOT / "manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n"
    )


if __name__ == "__main__":
    generate()
